export function localeCode(language: string): InterfaceLocale {
  const normalized = language.toLowerCase();
  if (normalized === "french" || normalized === "fr") return "fr";
  if (normalized === "arabic" || normalized === "ar") return "ar";
  return "en";
}

export function translateUi(message: string, language: string) {
  const locale = localeCode(language);
  if (locale === "en") return message;
  return CATALOGS[locale][message] ?? message;
}

export function translateWeekdayLabels(message: string, translate: (label: string) => string) {
  return message.replace(/\b(Sun|Mon|Tue|Wed|Thu|Fri|Sat)\b/g, (day) => translate(day));
}
